const LANG_KEY = 'pakka-lang'

/** Saved language, else English. */
export function initialLang() {
  try {
    const saved = window.localStorage.getItem(LANG_KEY)
    if (saved && STRINGS[saved]) return saved
  } catch {
    /* storage blocked */
  }
  return 'en'
}

export function saveLang(code) {
  document.documentElement.lang = code
  try {
    window.localStorage.setItem(LANG_KEY, code)
  } catch {
    /* storage blocked: the choice lasts for this visit */
  }
}

/** Fills {name} placeholders. */
export const fill = (text, vars = {}) => text.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m))

export const LangContext = createContext({ lang: 'en', s: STRINGS.en, setLang: () => {} })

/** { lang, s (the strings), setLang } for the current language. */
export const useI18n = () => useContext(LangContext)
